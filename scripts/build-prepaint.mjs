/**
 * Generate public/boot/prepaint.js from appearance.ts cycle lists
 * so theme/UI/font catalogs aren't hand-duplicated in nuxt.config.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const appearancePath = resolve(root, 'app/utils/appearance.ts')
const outDir = resolve(root, 'public/boot')
const outPath = resolve(outDir, 'prepaint.js')

const src = readFileSync(appearancePath, 'utf8')

/** Pull `id: '…'` values from an OPTIONS array (cycles are derived via .map). */
function extractOptionIds(constName) {
  const re = new RegExp(
    `export const ${constName}[^=]*=\\s*\\[([\\s\\S]*?)\\n\\]`,
    'm',
  )
  const m = src.match(re)
  if (!m) throw new Error(`build-prepaint: missing ${constName}`)
  const ids = [...m[1].matchAll(/\bid:\s*'([^']+)'/g)].map((x) => x[1])
  if (!ids.length) throw new Error(`build-prepaint: no ids in ${constName}`)
  return ids
}

const themes = extractOptionIds('THEME_OPTIONS')
const uis = extractOptionIds('UI_OPTIONS')
const fonts = extractOptionIds('FONT_OPTIONS')
const sizes = extractOptionIds('FONT_SIZE_OPTIONS')
const radii = extractOptionIds('RADIUS_OPTIONS')
const dens = extractOptionIds('DENSITY_OPTIONS')
const lines = extractOptionIds('LINE_OPTIONS')

/** theme id → swatch (same map applyAppearance writes into meta[name=theme-color]) */
function extractSwatches() {
  const m = src.match(/export const THEME_OPTIONS[^=]*=\s*\[([\s\S]*?)\n\]/m)
  if (!m) throw new Error('build-prepaint: missing THEME_OPTIONS')
  const out = {}
  for (const row of m[1].matchAll(/\bid:\s*'([^']+)'[^}]*?\bswatch:\s*'(#[0-9a-fA-F]{3,8})'/g)) {
    out[row[1]] = row[2]
  }
  for (const id of themes) {
    if (!out[id]) throw new Error(`build-prepaint: no swatch for theme ${id}`)
  }
  return out
}
const swatches = extractSwatches()

/** `export const UI_FONTS = { braun: '…', … }` */
function extractFlatRecord(constName) {
  const start = src.indexOf(`export const ${constName}`)
  if (start < 0) throw new Error(`build-prepaint: missing ${constName}`)
  const slice = src.slice(start, start + 12_000)
  const out = {}
  for (const m of slice.matchAll(/^\s{2}(\w+):\s*'((?:\\'|[^'])*)',/gm)) {
    out[m[1]] = m[2]
  }
  return out
}

/** Chrome × body font stacks (TYPE_FACES) for pre-JS font-family hints */
function extractTypeFaces() {
  const start = src.indexOf('export const TYPE_FACES')
  if (start < 0) throw new Error('build-prepaint: missing TYPE_FACES')
  const slice = src.slice(start, start + 16_000)
  const out = {}
  let currentUi = null
  for (const line of slice.split('\n')) {
    const ui = line.match(/^\s{2}(\w+):\s*\{/)
    if (ui) {
      currentUi = ui[1]
      out[currentUi] = {}
      continue
    }
    const face = line.match(/^\s{4}(\w+):\s*'((?:\\'|[^'])*)',/)
    if (face && currentUi) out[currentUi][face[1]] = face[2]
    if (/^\s{2}\},?\s*$/.test(line)) currentUi = null
  }
  return out
}

const uiFontStacks = extractFlatRecord('UI_FONTS')
const typeStacks = extractTypeFaces()

const js = `/* Generated by scripts/build-prepaint.mjs — do not edit by hand */
(function () {
  var root = document.documentElement
  // OS scheme / contrast resolve outside the try: if storage throws (blocked
  // storage, some private modes) the fallback must still honour them
  function mm(q) {
    try {
      return !!(window.matchMedia && window.matchMedia(q).matches)
    } catch (e) {
      return false
    }
  }
  function osTheme() {
    return mm('(prefers-contrast: more)') ? 'contrast' : mm('(prefers-color-scheme: dark)') ? 'dark' : 'light'
  }
  var swatches = ${JSON.stringify(swatches)}
  // Mobile status-bar colour from the resolved theme. This script runs before the
  // static theme-color metas are parsed; the first matching meta wins, so add one early.
  function setThemeColor(t) {
    var c = swatches[t]
    if (!c) return
    try {
      var m = document.createElement('meta')
      m.setAttribute('name', 'theme-color')
      m.setAttribute('content', c)
      document.head.appendChild(m)
    } catch (e) {}
  }
  var resolved = 'light'
  try {
    var raw = localStorage.getItem('neospace_local_prefs')
    var p = raw ? JSON.parse(raw) : {}
    if (!p || typeof p !== 'object') p = {}
    var map = { hc: 'contrast', electric: 'frost', forest: 'tank' }
    var ok = ${JSON.stringify(themes)}
    var uis = ${JSON.stringify(uis)}
    var fonts = ${JSON.stringify(fonts)}
    var t = p.theme || 'auto'
    if (map[t]) t = map[t]
    var u = uis.indexOf(p.ui) >= 0 ? p.ui : 'braun'
    var f = fonts.indexOf(p.font) >= 0 ? p.font : 'sans'
    // Suite look (ibm.tools.shared) wins over local prefs, same validation as readSuiteLook —
    // otherwise a theme picked in bruh / loom flashes the old NeoSpace look first
    try {
      var sraw = localStorage.getItem('ibm.tools.shared')
      var sb = sraw ? JSON.parse(sraw) : null
      if (sb && typeof sb === 'object' && !Array.isArray(sb)) {
        if (typeof sb.theme === 'string') {
          var st = map[sb.theme] || sb.theme
          if (st === 'auto' || ok.indexOf(st) >= 0) t = st
        }
        if (typeof sb.ui === 'string' && uis.indexOf(sb.ui) >= 0) u = sb.ui
        if (typeof sb.font === 'string' && fonts.indexOf(sb.font) >= 0) f = sb.font
      }
    } catch (e) {}
    if (t === 'auto' || ok.indexOf(t) < 0) t = osTheme()
    resolved = t
    root.setAttribute('data-theme', t)
    root.setAttribute('data-ui', u)
    root.setAttribute('data-font', f)
    var uiFontStacks = ${JSON.stringify(uiFontStacks)}
    var typeStacks = ${JSON.stringify(typeStacks)}
    var uiStack = uiFontStacks[u]
    var typeStack = typeStacks[u] && typeStacks[u][f]
    if (uiStack) root.style.setProperty('--neo-font-family-ui', uiStack)
    if (typeStack) {
      root.style.setProperty('--neo-font-family', typeStack)
      root.style.setProperty('--neo-font-family-heading', typeStack)
    }
    var sizes = ${JSON.stringify(sizes)}
    var s = sizes.indexOf(p.fontSize) >= 0 ? p.fontSize : 'medium'
    root.setAttribute('data-font-size', s)
    var radii = ${JSON.stringify(radii)}
    var r = radii.indexOf(p.radius) >= 0 ? p.radius : 'match'
    root.setAttribute('data-radius', r)
    var dens = ${JSON.stringify(dens)}
    var d = dens.indexOf(p.density) >= 0 ? p.density : p.compactMode ? 'dense' : 'cozy'
    root.setAttribute('data-density', d)
    if (d === 'dense') root.classList.add('compact-mode')
    var lines = ${JSON.stringify(lines)}
    var ln = lines.indexOf(p.line) >= 0 ? p.line : 'clean'
    root.setAttribute('data-line', ln)
    if (p.reduceMotion) root.classList.add('reduce-motion')
    if (localStorage.getItem('neospace_sidebar_rail') === '1') {
      root.setAttribute('data-rail', '')
      root.style.setProperty('--neo-sidebar-width', '68px')
    }
  } catch (e) {
    resolved = osTheme()
    root.setAttribute('data-theme', resolved)
    root.setAttribute('data-ui', 'braun')
    root.setAttribute('data-font', 'sans')
    root.setAttribute('data-font-size', 'medium')
    root.setAttribute('data-radius', 'match')
    root.setAttribute('data-density', 'cozy')
    root.setAttribute('data-line', 'clean')
  }
  setThemeColor(resolved)
})()
`

mkdirSync(outDir, { recursive: true })
writeFileSync(outPath, js)
console.log('build-prepaint: wrote', outPath)
