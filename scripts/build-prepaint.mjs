/**
 * Generate public/boot/prepaint.js from appearance.ts cycle lists
 * so theme/UI/font catalogs aren't hand-duplicated in nuxt.config.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const appearancePath = resolve(root, 'app/utils/appearance.ts')
const outDir = resolve(root, 'public/boot')
const outPath = resolve(outDir, 'prepaint.js')

const src = readFileSync(appearancePath, 'utf8')

/** Pull `id: '…'` values from an OPTIONS array (cycles are derived via .map). */
function extractOptionIds(constName) {
  const re = new RegExp(
    `export const ${constName}[^=]*=\\s*\\[([\\s\\S]*?)\\n\\]`,
    'm',
  )
  const m = src.match(re)
  if (!m) throw new Error(`build-prepaint: missing ${constName}`)
  const ids = [...m[1].matchAll(/\bid:\s*'([^']+)'/g)].map((x) => x[1])
  if (!ids.length) throw new Error(`build-prepaint: no ids in ${constName}`)
  return ids
}

const themes = extractOptionIds('THEME_OPTIONS')
const uis = extractOptionIds('UI_OPTIONS')
const fonts = extractOptionIds('FONT_OPTIONS')
const sizes = extractOptionIds('FONT_SIZE_OPTIONS')
const radii = extractOptionIds('RADIUS_OPTIONS')
const dens = extractOptionIds('DENSITY_OPTIONS')
const lines = extractOptionIds('LINE_OPTIONS')

const js = `/* Generated by scripts/build-prepaint.mjs — do not edit by hand */
(function () {
  try {
    var raw = localStorage.getItem('neospace_local_prefs')
    var p = raw ? JSON.parse(raw) : {}
    var map = { hc: 'contrast', electric: 'frost', forest: 'tank' }
    var t = p.theme || 'auto'
    if (map[t]) t = map[t]
    var ok = ${JSON.stringify(themes)}
    if (t === 'auto' || ok.indexOf(t) < 0) {
      if (window.matchMedia && window.matchMedia('(prefers-contrast: more)').matches) t = 'contrast'
      else
        t =
          window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches
            ? 'dark'
            : 'light'
    }
    document.documentElement.setAttribute('data-theme', t)
    var uis = ${JSON.stringify(uis)}
    var u = uis.indexOf(p.ui) >= 0 ? p.ui : 'braun'
    document.documentElement.setAttribute('data-ui', u)
    var fonts = ${JSON.stringify(fonts)}
    var f = fonts.indexOf(p.font) >= 0 ? p.font : 'sans'
    document.documentElement.setAttribute('data-font', f)
    var sizes = ${JSON.stringify(sizes)}
    var s = sizes.indexOf(p.fontSize) >= 0 ? p.fontSize : 'medium'
    document.documentElement.setAttribute('data-font-size', s)
    var radii = ${JSON.stringify(radii)}
    var r = radii.indexOf(p.radius) >= 0 ? p.radius : 'match'
    document.documentElement.setAttribute('data-radius', r)
    var dens = ${JSON.stringify(dens)}
    var d = dens.indexOf(p.density) >= 0 ? p.density : p.compactMode ? 'dense' : 'cozy'
    document.documentElement.setAttribute('data-density', d)
    if (d === 'dense') document.documentElement.classList.add('compact-mode')
    var lines = ${JSON.stringify(lines)}
    var ln = lines.indexOf(p.line) >= 0 ? p.line : 'clean'
    document.documentElement.setAttribute('data-line', ln)
    if (p.reduceMotion) document.documentElement.classList.add('reduce-motion')
    if (localStorage.getItem('neospace_sidebar_rail') === '1') {
      document.documentElement.setAttribute('data-rail', '')
      document.documentElement.style.setProperty('--neo-sidebar-w', '68px')
    }
  } catch (e) {
    document.documentElement.setAttribute('data-theme', 'light')
    document.documentElement.setAttribute('data-ui', 'braun')
    document.documentElement.setAttribute('data-font', 'sans')
    document.documentElement.setAttribute('data-radius', 'match')
    document.documentElement.setAttribute('data-density', 'cozy')
    document.documentElement.setAttribute('data-line', 'clean')
  }
})()
`

mkdirSync(outDir, { recursive: true })
writeFileSync(outPath, js)
console.log('build-prepaint: wrote', outPath)
